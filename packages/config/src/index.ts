/**
 * Typed, validated environment configuration.
 *
 * Every process (api, worker, web) imports from here rather than reading
 * process.env directly. A missing or malformed variable fails loudly at
 * boot instead of surfacing as `undefined` three layers deep at 2am.
 */
import { config as loadDotenv } from 'dotenv';
import { z } from 'zod';
import { resolve } from 'node:path';

loadDotenv({ path: resolve(process.cwd(), '../../.env') });
loadDotenv();

const booleanish = z
  .enum(['true', 'false'])
  .transform((v) => v === 'true')
  .or(z.boolean());

const envSchema = z.object({
  NODE_ENV: z.enum(['development', 'test', 'production']).default('development'),
  LOG_LEVEL: z.enum(['fatal', 'error', 'warn', 'info', 'debug', 'trace']).default('info'),

  DATABASE_URL: z.string().url(),
  REDIS_URL: z.string().url(),

  /** 32-byte base64 key protecting stored platform session cookies. */
  PF_ENCRYPTION_KEY: z.string().min(32, 'PF_ENCRYPTION_KEY must be a 32-byte base64 string'),

  BETTER_AUTH_SECRET: z.string().min(16),
  BETTER_AUTH_URL: z.string().url(),

  /**
   * The owner's API token. Every /api request must send
   * `Authorization: Bearer <token>`. Generated by scripts/generate-secrets.mjs.
   */
  PF_API_TOKEN: z.string().min(32, 'PF_API_TOKEN must be at least 32 characters'),

  /** From @BotFather. Leave empty to run without Telegram. */
  TELEGRAM_BOT_TOKEN: z
    .string()
    .optional()
    .transform((v) => v || undefined),
  /** The only chat the bot will talk to. The bot tells you yours on /start. */
  TELEGRAM_OWNER_CHAT_ID: z
    .string()
    .optional()
    .transform((v) => v || undefined),
  /** Local hour (0-23) for the daily summary, in OWNER_TIMEZONE. */
  DAILY_SUMMARY_HOUR: z.coerce.number().int().min(0).max(23).default(20),
  OWNER_TIMEZONE: z.string().default('Africa/Lagos'),

  /**
   * How post drafts are written:
   * - claude-code: the Claude Code CLI (`claude -p`) logged in with the owner's
   *   Claude subscription - no per-use API cost. For the owner's own accounts.
   * - api: the Anthropic API with ANTHROPIC_API_KEY, billed per use.
   */
  DRAFT_ENGINE: z.enum(['claude-code', 'api']).default('claude-code'),
  /** The Claude Code command; set a full path if `claude` isn't on PATH. */
  CLAUDE_CLI: z.string().default('claude'),
  /** Only for DRAFT_ENGINE=api. */
  ANTHROPIC_API_KEY: z
    .string()
    .optional()
    .transform((v) => v || undefined),
  /** Local hour (0-23, OWNER_TIMEZONE) when auto-draft tops up waiting drafts. */
  DRAFT_HOUR: z.coerce.number().int().min(0).max(23).default(8),
  /** How many Claude drafts auto-draft keeps waiting per account. */
  DRAFTS_WAITING: z.coerce.number().int().min(1).max(10).default(3),

  API_PORT: z.coerce.number().int().positive().default(3001),
  API_URL: z.string().url(),
  WEB_URL: z.string().url(),

  S3_ENDPOINT: z.string().url(),
  S3_REGION: z.string().default('us-east-1'),
  S3_BUCKET: z.string(),
  S3_ACCESS_KEY_ID: z.string(),
  S3_SECRET_ACCESS_KEY: z.string(),
  S3_FORCE_PATH_STYLE: booleanish.default(true),

  WORKER_CONCURRENCY: z.coerce.number().int().positive().default(2),
  PLAYWRIGHT_HEADLESS: booleanish.default(true),
  RUN_TIMEOUT_MS: z.coerce.number().int().positive().default(900_000),

  QUOTA_CONNECTIONS_PER_DAY: z.coerce.number().int().nonnegative().default(20),
  /** Rolling 7-day cap on connection requests; LinkedIn's own weekly cap is ~100. */
  QUOTA_CONNECTIONS_PER_WEEK: z.coerce.number().int().nonnegative().default(80),
  QUOTA_MESSAGES_PER_DAY: z.coerce.number().int().nonnegative().default(30),
  QUOTA_PROFILE_VIEWS_PER_DAY: z.coerce.number().int().nonnegative().default(80),
  QUOTA_POSTS_PER_DAY: z.coerce.number().int().nonnegative().default(3),
  PACING_MIN_MS: z.coerce.number().int().nonnegative().default(8_000),
  PACING_MAX_MS: z.coerce.number().int().nonnegative().default(25_000),
});

export type Env = z.infer<typeof envSchema>;

function parseEnv(): Env {
  const parsed = envSchema.safeParse(process.env);
  if (!parsed.success) {
    const issues = parsed.error.issues
      .map((i) => `  - ${i.path.join('.')}: ${i.message}`)
      .join('\n');
    throw new Error(
      `Invalid environment configuration:\n${issues}\n\n` +
        'Copy .env.example to .env and fill in the missing values.',
    );
  }
  return parsed.data;
}

export const env: Env = parseEnv();

export const isProduction = env.NODE_ENV === 'production';
export const isDevelopment = env.NODE_ENV === 'development';

/** Whether post drafting is configured (the CLI engine is checked when it runs). */
export const draftingEnabled = env.DRAFT_ENGINE === 'claude-code' || Boolean(env.ANTHROPIC_API_KEY);
export const draftingOffReason = 'Drafting is off: DRAFT_ENGINE=api but ANTHROPIC_API_KEY is empty in the server .env.';
